def bodymap(view, hi, title='', crop=(0, 400), scale=1.15):
    """view: 'front' / 'back'；hi: [(muscle_id, level, label, side)]，level 1 主要 / 2 协同，side 'L' / 'R'。
    返回 (svg 片段, 高度)。画在 360 宽的画布中央。"""
    shapes = FRONT if view == 'front' else BACK
    lv = {m: l for m, l, *_ in hi}
    y0, y1 = crop
    top = 24 if title else 4
    cx = 180

    def half(mirror):
        tr = f'translate({cx + 90 * scale:.1f},{top - y0 * scale:.1f}) scale({-scale},{scale})' if mirror else \
             f'translate({cx - 90 * scale:.1f},{top - y0 * scale:.1f}) scale({scale})'
        g = [f'<g transform="{tr}">', P(SIL, 'f-body')]
        for mid, (d, _) in shapes.items():
            cls = {1: 'f-hi', 2: 'f-hi2'}.get(lv.get(mid), 'f-off')
            g.append(f'<path d="{d}" class="{cls}" stroke="var(--fig-body)" stroke-width="1"/>')
        g.append('</g>')
        return ''.join(g)
    h = (y1 - y0) * scale + top + 6
    o = [f'<clipPath id="bm-{view}-{y0}-{y1}-{len(hi)}"><rect x="0" y="{top}" width="360" height="{(y1 - y0) * scale + 2:.1f}"/></clipPath>',
         f'<g clip-path="url(#bm-{view}-{y0}-{y1}-{len(hi)})">', half(False), half(True)]
    if y0 < 44:
        o.append(f'<ellipse cx="{cx}" cy="{top + (26 - y0) * scale:.1f}" rx="{14 * scale:.1f}" ry="{17 * scale:.1f}" class="f-body"/>')
    o.append('</g>')
    if title:
        o.append(T(0, 14, title, 't tb'))
    # 标签与引线
    labs = {'L': [], 'R': []}
    for mid, level, label, side in hi:
        if not label:
            continue
        ax, ay = shapes[mid][1]
        gx = cx + (ax - 90) * scale * (1 if side == 'R' else -1)
        gy = top + (ay - y0) * scale
        labs[side].append([gy, gx, gy, label, level])
    for side, arr in labs.items():
        arr.sort()
        for i in range(1, len(arr)):
            if arr[i][0] - arr[i - 1][0] < 17:
                arr[i][0] = arr[i - 1][0] + 17
        for ly, gx, gy, label, level in arr:
            ly = min(max(ly, top + 10), h - 8)
            ex = 262 if side == 'R' else 98
            o.append(L(gx, gy, ex + (-3 if side == 'R' else 3), ly - 3.5, 's-ink', 0.8))
            o.append(C(gx, gy, 2.2, 'f-ink'))
            o.append(T(ex, ly, label, 'ts tb' if level == 1 else 'ts', 'start' if side == 'R' else 'end'))
    return ''.join(o), h


def _reg(name, view, hi, title, crop=(0, 400), scale=1.15):
    body, h = bodymap(view, hi, title, crop, scale)
    fig(name, 360, int(h))(lambda: body)


